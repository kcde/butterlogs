// Generates src/styles/tokens.css from design/tokens.json (the design
// system's tokens). Run with `npm run tokens`; never edit tokens.css by hand.
//
// Every token becomes a CSS variable with the same name (--caramel,
// --space-4, --radius-card…). Light values go on :root and dark values in
// prefers-color-scheme: dark, because the app follows the phone's setting.
// Type styles become font shorthands (--type-title) so any CSS module can use
// them with `font: var(--type-title)`.

import { readFileSync, writeFileSync } from "node:fs";

const source = new URL("../design/tokens.json", import.meta.url);
const target = new URL("../src/styles/tokens.css", import.meta.url);
const tokens = JSON.parse(readFileSync(source, "utf8"));

// "{ink}" refers to another token.
const value = (v) => (/^\{.+\}$/.test(v) ? `var(--${v.slice(1, -1)})` : v);

const light = [];
const dark = [];

for (const { name, value: v } of tokens.color.tokens) {
  light.push(`--${name}: ${value(v.light)};`);
  if (v.dark !== v.light) dark.push(`--${name}: ${value(v.dark)};`);
}
for (const { name, value: v } of tokens.shadow.tokens) {
  light.push(`--${name}: ${v.light};`);
  dark.push(`--${name}: ${v.dark};`);
}
for (const group of ["spacing", "radius", "size"]) {
  for (const { name, value: v } of tokens[group].tokens) light.push(`--${name}: ${v};`);
}
// --font-sans comes from next/font (Noto Sans, bundled with the app).
for (const { styles } of tokens.type.groups) {
  for (const s of styles) {
    light.push(`--type-${s.name}: ${s.fontWeight} ${s.fontSize}/${s.lineHeight} var(--font-sans);`);
    if (s.letterSpacing) light.push(`--type-${s.name}-tracking: ${s.letterSpacing};`);
  }
}

const block = (lines, indent) => lines.map((line) => `${indent}${line}`).join("\n");
const css = `/* Generated by scripts/tokens.mjs from design/tokens.json. Don't edit: run \`npm run tokens\`. */

:root {
${block(light, "  ")}
}

@media (prefers-color-scheme: dark) {
  :root {
${block(dark, "    ")}
  }
}
`;

writeFileSync(target, css);
console.log(`Wrote ${target.pathname} (${light.length} tokens, ${dark.length} dark overrides)`);
